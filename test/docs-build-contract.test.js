test("docs package is isolated, exact-pinned, and complete", async () => {
  await Promise.all(required.map((path) => access(new URL(path, docs))));
  const pkg = JSON.parse(await readFile(new URL("package.json", docs)));
  assert.equal(pkg.private, true);
  assert.equal(pkg.type, "module");
  assert.deepEqual(pkg.engines, { node: ">=22.12.0" });
  assert.deepEqual(pkg.devDependencies, {
    "@astrojs/check": "0.9.9",
    "@playwright/test": "1.62.0",
    astro: "7.1.3",
    typescript: "6.0.3",
  });
  const lock = JSON.parse(await readFile(new URL("package-lock.json", docs)));
  assert.equal(lock.lockfileVersion, 3);
  assert.ok(Object.values(lock.packages).some((value) => value?.integrity));
  const rootPkg = JSON.parse(await readFile(new URL("package.json", root)));
  assert.ok(!rootPkg.dependencies || Object.keys(rootPkg.dependencies).length === 0);
});

