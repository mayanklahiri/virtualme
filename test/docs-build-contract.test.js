test("disabled/enabled analytics builds are complete and disabled output is deterministic", async () => {
  const cwd = new URL("../docs/", import.meta.url).pathname;
  const build = (measurementId = "") => spawnSync("npm", ["run", "build"], {
    cwd,
    encoding: "utf8",
    env: { ...process.env, PUBLIC_GA_MEASUREMENT_ID: measurementId },
  });
  async function htmlFiles(directory) {
    const result = [];
    async function visit(path) {
      for (const entry of await readdir(path, { withFileTypes: true })) {
        const child = join(path, entry.name);
        if (entry.isDirectory()) await visit(child);
        else if (entry.name.endsWith(".html")) result.push(child);
      }
    }
    await visit(directory);
    return result.sort((a, b) => Buffer.from(a).compare(Buffer.from(b)));
  }
  async function digestTree(directory) {
    const result = new Map();
    async function visit(path) {
      for (const entry of await readdir(path, { withFileTypes: true })) {
        const child = join(path, entry.name);
        if (entry.isDirectory()) await visit(child);
        else result.set(relative(directory, child), createHash("sha256").update(await readFile(child)).digest("hex"));
      }
    }
    await visit(directory);
    return result;
  }
  let run = build();
  assert.equal(run.status, 0, run.stderr);
  const first = await digestTree(join(cwd, "dist"));
  for (const file of await htmlFiles(join(cwd, "dist"))) assert.doesNotMatch(await readFile(file, "utf8"), /googletagmanager|google-analytics|dataLayer|gtag\(/);
  run = build();
  assert.equal(run.status, 0, run.stderr);
  assert.deepEqual(await digestTree(join(cwd, "dist")), first);
  run = build("G-TEST1234");
  assert.equal(run.status, 0, run.stderr);
  for (const file of await htmlFiles(join(cwd, "dist"))) {
    const html = await readFile(file, "utf8");
    assert.equal((html.match(/googletagmanager\.com\/gtag\/js\?id=G-TEST1234/g) ?? []).length, 1, file);
    assert.equal((html.match(/gtag\("config",\s*analyticsMeasurementId\)/g) ?? []).length, 1, file);
  }
  run = build("not-valid");
  assert.notEqual(run.status, 0);
  const verifier = await readFile(new URL("scripts/verify-build.mjs", docs), "utf8");
  assert.doesNotMatch(verifier, /G-TEST1234/);
  assert.match(verifier, /committedAnalyticsId/);
});
