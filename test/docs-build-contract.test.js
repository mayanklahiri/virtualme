test("authored Astro sources stay docs-local and contain no remote resources", async () => {
  async function walk(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    return (await Promise.all(entries.map((entry) => entry.isDirectory()
      ? walk(new URL(`${entry.name}/`, directory))
      : [new URL(entry.name, directory)]))).flat();
  }
  const files = (await walk(new URL("src/", docs))).filter((url) => /\.(astro|ts|js|md|mdx)$/.test(url.pathname));
  for (const file of files) {
    const text = await readFile(file, "utf8");
    assert.doesNotMatch(text, /from\s+["'][^"']*(?:\.\.\/){3}|readFile|fetch\s*\(/, file.pathname);
    assert.doesNotMatch(text, /\bsrc=["']https?:\/\//, file.pathname);
    assert.doesNotMatch(text, /(?:href|src)=["']\/(?!\/)/, file.pathname);
    if (/\.(?:md|mdx)$/.test(file.pathname)) {
      for (const match of text.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)) {
        const target = match[1];
        assert.doesNotMatch(target, /^\/virtualme\//, file.pathname);
        if (!/^(?:https?:|mailto:|tel:|#)/.test(target)) assert.match(target, /^site:[a-z0-9][a-z0-9/.-]*$/i, file.pathname);
      }
    }
  }
});

